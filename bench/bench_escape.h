// "Непрозрачная" для компилятора функция-приёмник.
//
// Без неё на -O2 GCC/Clang легально выкидывают циклы вида
// "new T(...); ...; delete p;", если результат никуда не используется —
// это разрешённая стандартом элизия аллокации. В итоге замер честно
// покажет 0 мс там, где на самом деле происходят миллионы new/delete.
// Передавая указатель/значение сюда на каждой итерации, мы не даём
// компилятору доказать отсутствие наблюдаемого эффекта: функция определена
// в отдельном .cpp и не инлайнится (LTO в проекте не включён), так что для
// компилятора её последствия неизвестны.
void bench_escape(const void* p);
